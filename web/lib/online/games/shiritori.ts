const WORD_SET = new Set(SHIRITORI_WORDS);

const SMALL_TO_LARGE: Record<string, string> = {
  ァ: "ア", ィ: "イ", ゥ: "ウ", ェ: "エ", ォ: "オ",
  ャ: "ヤ", ュ: "ユ", ョ: "ヨ", ッ: "ツ", ヮ: "ワ",
};

/** 入力を正規化する: 空白除去＋ひらがな→カタカナ。 */
export function normalizeShiritoriWord(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const stripped = raw.replace(/[\s　]/g, "");
  if (stripped.length === 0) return null;
  let out = "";
  for (const ch of stripped) {
    const code = ch.codePointAt(0) as number;
    // ひらがな（ぁ〜ん）をカタカナへ。
    if (code >= 0x3041 && code <= 0x3096) {
      out += String.fromCodePoint(code + 0x60);
    } else {
      out += ch;
    }
  }
  return out;
}

/** 単語の形式チェック（カタカナ・長音のみ、2〜10文字）。 */
export function isValidWordForm(word: string): boolean {
  return word.length >= 2 && word.length <= 10 && /^[ァ-ヶー]+$/.test(word);
}

/**
 * しりとりの接続に使う最後の文字。
 * 末尾の「ー」を取り除き、小さい文字は大きい文字に読み替える。
 */
export function shiritoriTail(word: string): string {
  let w = word;
  while (w.length > 1 && w.endsWith("ー")) w = w.slice(0, -1);
  const last = w.charAt(w.length - 1);
  return SMALL_TO_LARGE[last] ?? last;
}

/** バンクにある単語かどうか。 */
export function isBankWord(word: string): boolean {
  return WORD_SET.has(word);
}

export type ShiritoriEvent =
  | { kind: "word"; seat: number; word: string }
  | { kind: "n-foul"; seat: number; word: string }
  | { kind: "timeout"; seat: number }
  | { kind: "left"; seat: number };

export interface ShiritoriHistoryEntry {
  seat: number;
  word: string;
  /** 「ン」で終わって脱落した提出。 */
  foul: boolean;
}

export interface ShiritoriState {
  players: SeatInfo[];
  turn: number;
  /** 現在のターンの締切（epoch ms）。 */
  turnEndsAt: number;
  /** 次の単語の開始文字。初回は null（自由）。 */
  requiredStart: string | null;
  history: ShiritoriHistoryEntry[];
  /** 提出済み単語（重複判定用）。 */
  used: string[];
  eliminated: number[];
  leftSeats: number[];
  finished: boolean;
  winner: number | null;
  lastEvent: ShiritoriEvent | null;
}

export type ShiritoriAction = { type: "submit"; word: string };

export interface ShiritoriPlayerView {
  seat: number;
  name: string;
  alive: boolean;
  left: boolean;
  isTurn: boolean;
}

export interface ShiritoriView {
  phase: "playing" | "finished";
  turn: number;
  turnEndsAt: number | null;
  requiredStart: string | null;
  history: ShiritoriHistoryEntry[];
  you: { seat: number; alive: boolean; left: boolean; isTurn: boolean };
  players: ShiritoriPlayerView[];
  finished: boolean;
  winner: number | null;
  lastEvent: ShiritoriEvent | null;
  playersInfo: SeatInfo[];
}

function shiClone<T>(value: T): T {
  return JSON.parse(JSON.stringify(value)) as T;
}

function isAlive(state: ShiritoriState, seat: number): boolean {
  return !state.eliminated.includes(seat) && !state.leftSeats.includes(seat);
}

function aliveSeats(state: ShiritoriState): number[] {
  const out: number[] = [];
  for (let s = 0; s < state.players.length; s++) {
    if (isAlive(state, s)) out.push(s);
  }
  return out;
}

function nextAlive(state: ShiritoriState, seat: number): number {
  const n = state.players.length;
  for (let step = 1; step <= n; step++) {
    const s = (seat + step) % n;
    if (isAlive(state, s)) return s;
  }
  return seat;
}

/** 生存が1人以下なら終局にする。変化があれば true。 */
function settleEnd(draft: ShiritoriState): boolean {
  const alive = aliveSeats(draft);
  if (alive.length > 1) return false;
  draft.finished = true;
  draft.winner = alive.length === 1 ? alive[0] : null;
  return true;
}

/** 手番を次の生存者へ進め、制限時間をリセットする（draft を破壊的に更新）。 */
function advanceTurn(draft: ShiritoriState, now: number): void {
  if (settleEnd(draft)) return;
  draft.turn = nextAlive(draft, draft.turn);
  draft.turnEndsAt = now + SHIRITORI_TURN_MS;
}

function createState(players: SeatInfo[], _rng: Rng, _options: Record<string, unknown>): ShiritoriState {
  if (!Array.isArray(players) || players.length < 2 || players.length > 6) {
    throw new Error("しりとりは2〜6人で遊びます");
  }
  const sorted = shiClone(players).sort((a, b) => a.seat - b.seat);
  return {
    players: sorted,
    turn: sorted[0].seat,
    turnEndsAt: Date.now() + SHIRITORI_TURN_MS,
    requiredStart: null,
    history: [],
    used: [],
    eliminated: [],
    leftSeats: [],
    finished: false,
    winner: null,
    lastEvent: null,
  };
}

function applyAction(state: ShiritoriState, seat: number, action: ShiritoriAction, _rng: Rng): ShiritoriState {
  if (state.finished) throw new Error("ゲームは終了しています");
  if (!Number.isInteger(seat) || seat < 0 || seat >= state.players.length) {
    throw new Error("不正な席です");
  }
  if (!action || typeof action !== "object" || action.type !== "submit") {
    throw new Error("不正なアクションです");
  }
  if (!isAlive(state, seat)) throw new Error("既に脱落しています");
  if (seat !== state.turn) throw new Error("あなたの番ではありません");
  const now = Date.now();
  if (now > state.turnEndsAt) throw new Error("制限時間を過ぎています");

  const word = normalizeShiritoriWord(action.word);
  if (word === null || !isValidWordForm(word)) {
    throw new Error("カタカナの単語（2〜10文字）で入力してください");
  }
  if (!isBankWord(word)) throw new Error("単語バンクにない言葉です");
  if (state.used.includes(word)) throw new Error("その単語はもう使われています");
  if (state.requiredStart !== null && word.charAt(0) !== state.requiredStart) {
    throw new Error(`「${state.requiredStart}」から始まる単語を出してください`);
  }

  const next = shiClone(state);
  const foul = word.endsWith("ン");
  next.history.push({ seat, word, foul });
  next.used.push(word);
  if (foul) {
    // 「ン」で終わったら脱落。接続先（requiredStart）は前の単語のまま据え置く。
    next.eliminated.push(seat);
    next.lastEvent = { kind: "n-foul", seat, word };
  } else {
    next.requiredStart = shiritoriTail(word);
    next.lastEvent = { kind: "word", seat, word };
  }
  advanceTurn(next, now);
  return next;
}

function viewFor(state: ShiritoriState, seat: number): ShiritoriView {
  return {
    phase: state.finished ? "finished" : "playing",
    turn: state.turn,
    turnEndsAt: state.finished ? null : state.turnEndsAt,
    requiredStart: state.requiredStart,
    history: shiClone(state.history),
    you: {
      seat,
      alive: isAlive(state, seat),
      left: state.leftSeats.includes(seat),
      isTurn: !state.finished && state.turn === seat,
    },
    players: state.players.map((p) => ({
      seat: p.seat,
      name: p.name,
      alive: isAlive(state, p.seat),
      left: state.leftSeats.includes(p.seat),
      isTurn: !state.finished && state.turn === p.seat,
    })),
    finished: state.finished,
    winner: state.winner,
    lastEvent: state.lastEvent ? shiClone(state.lastEvent) : null,
    playersInfo: shiClone(state.players),
  };
}

function parseAction(raw: unknown): ShiritoriAction | null {
  if (!raw || typeof raw !== "object") return null;
  const r = raw as Record<string, unknown>;
  if (r.type !== "submit") return null;
  if (typeof r.word !== "string" || r.word.length === 0 || r.word.length > 40) return null;
  return { type: "submit", word: r.word };
}

function onPlayerLeft(state: ShiritoriState, seat: number): ShiritoriState {
  if (!Number.isInteger(seat) || seat < 0 || seat >= state.players.length) {
    throw new Error("不正な席です");
  }
  if (state.finished) return shiClone(state);
  if (!isAlive(state, seat)) return shiClone(state);
  const next = shiClone(state);
  next.leftSeats.push(seat);
  next.lastEvent = { kind: "left", seat };
  if (!settleEnd(next) && next.turn === seat) {
    next.turn = nextAlive(next, seat);
    next.turnEndsAt = Date.now() + SHIRITORI_TURN_MS;
  }
  return next;
}

function tick(state: ShiritoriState, now: number): ShiritoriState {
  if (state.finished) return state;
  if (now < state.turnEndsAt) return state;
  const next = shiClone(state);
  const victim = next.turn;
  next.eliminated.push(victim);
  next.lastEvent = { kind: "timeout", seat: victim };
  advanceTurn(next, now);
  return next;
}

