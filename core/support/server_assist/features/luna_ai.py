async def _build_user_content(prompt: str, attachments: list[Any]) -> Any:
    if not attachments:
        return prompt
    has_images = ai_input.has_image_attachment(attachments)
    if has_images and not await _images_supported():
        return prompt + "\n（画像が添付された。ただし Luna は画像そのものを見ることはできない）"
    try:
        return await ai_input.build_user_content(prompt, attachments, images_supported=True)
    except ai_input.AttachmentInputError:
        return prompt


def _link_blocks(links: list[Any]) -> str:
    blocks: list[str] = []
    for index, link in enumerate(links, 1):
        if link.error:
            blocks.append(f"【参照リンク {index}: {link.url}】\n取得失敗: {link.error}")
            continue
        title = f"タイトル: {link.title}\n" if link.title else ""
        blocks.append(f"【参照リンク {index}: {link.final_url or link.url}】\n{title}{link.text}")
    return "\n\n".join(blocks)


