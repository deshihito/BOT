PROBABILITY_OPTIONS = (0, 10, 25, 50, 75, 90, 100)


class LunaProbabilitySelect(discord.ui.Select):
    """返信確率（バッチごとの抽選）のプリセット選択。"""

    def __init__(self, current: int) -> None:
        options = [
            discord.SelectOption(label=f"{value}%", value=str(value), default=value == current)
            for value in PROBABILITY_OPTIONS
        ]
        super().__init__(placeholder=f"返信確率を選ぶ（現在 {current}%）", options=options, row=3)

    async def callback(self, interaction: discord.Interaction) -> None:
        view: LunaSettingsView = self.view
        if not view.can_manage(interaction):
            return await interaction.response.send_message(
                ASSIST_MANAGE_REQUIRED, ephemeral=True)
        value = int(self.values[0])
        await update_settings(view.guild_id, KEY, reply_probability=value)
        return await view.reopen(interaction, f"返信確率を {value}% にしました。")


class LunaSettingsView(AssistFeatureView):
    """有効化・設置チャンネル・リセット・カスタム人格をまとめた設定ビュー。"""

    feature_key = KEY

    def __init__(self, cog: Any, guild_id: int) -> None:
        self.settings = settings(guild_id)
        super().__init__(cog, guild_id)
        self.add_item(AssistChannelSelect(
            self, field="channel_id", placeholder="Luna を設置するチャンネル",
            notice=lambda cid: (
                f"<#{cid}> を Luna の設置チャンネルにしました。" if cid
                else "Luna の設置を取り消しました。"),
            min_values=0, row=0, check="send", reopen=True))
        self.add_item(AssistToggleButton("enabled", "Luna AI", row=1, reopen=True))
        self.add_item(LunaResetButton())
        self.add_item(LunaCustomButton())
        self.add_item(LunaCustomDeleteButton(disabled=self.settings["custom"] is None))
        self.add_item(LunaProbabilitySelect(self.settings["reply_probability"]))

    async def reopen(self, interaction: discord.Interaction, notice: str | None = None):
        view = LunaSettingsView(self.cog, self.guild_id)
        view.notice = notice
        return await edit_panel_v2(interaction, as_panel_v2(view))

    def embed(self) -> discord.Embed:
        current = self.settings
        channel_line = f"<#{current['channel_id']}>" if current["channel_id"] else "未設定"
        custom = current["custom"]
        persona_line = f"カスタム「{custom['name']}」" if custom else "既定（Luna）"
        return discord.Embed(
            title="Luna AI",
            description=(
                "設置したチャンネルで人が話すと、Luna が会話に応答します。"
                f"\n\n**状態**: {'オン' if current['enabled'] else 'オフ'}"
                f"\n**設置チャンネル**: {channel_line}"
                f"\n**人格**: {persona_line}"
                f"\n**返信確率**: {current['reply_probability']}%"
                + notice_line(self.notice)
            )[:4096],
            color=0xFFFFFF,
        )


def build_view(cog: Any, guild_id: int) -> LunaSettingsView:
    return LunaSettingsView(cog, guild_id)
