# ---------------------------------------------------------------- 応答分割（純関数）

def split_response(text: Any, *, max_parts: int = MAX_SEND_PARTS, limit: int = 2000) -> list[str]:
    """応答を行単位で最大 max_parts 通に分割する。空行は落とす。"""
    units: list[str] = []
    for line in str(text or "").splitlines():
        unit = line.strip()
        if not unit:
            continue
        while len(unit) > limit:
            units.append(unit[:limit])
            unit = unit[limit:]
        if unit:
            units.append(unit)
    if not units:
        return []
    if len(units) <= max_parts:
        return units
    # 行数が上限を超える場合は、行を均等に分けて max_parts 通にする
    # （1通に潰さない）。1通が上限字数を超える場合だけ貪欲に詰め直す。
    group = -(-len(units) // max_parts)
    parts = ["\n".join(units[i:i + group]) for i in range(0, len(units), group)]
    if all(len(part) <= limit for part in parts):
        return parts[:max_parts]
    packed: list[str] = []
    current = ""
    for unit in units:
        candidate = unit if not current else f"{current}\n{unit}"
        if len(candidate) <= limit or not current:
            current = candidate
        elif len(packed) < max_parts - 1:
            packed.append(current)
            current = unit
        # 最後の1通に入りきらない分は落とす（人格の応答は短い前提）
    if current:
        packed.append(current)
    return packed[:max_parts]


# ---------------------------------------------------------------- 常駐ランタイム

@dataclass
class _Runtime:
    guild_id: int
    channel: Any
    pending: list[Any] = field(default_factory=list)
    append_tasks: list[asyncio.Task] = field(default_factory=list)
    last_message_at: float | None = None
    last_turn_at: float | None = None
    last_reply_at: float | None = None
    reply_times: deque = field(default_factory=deque)
    task: asyncio.Task | None = None
    idle_task: asyncio.Task | None = None
    seeded: bool = False


_runtimes: dict[int, _Runtime] = {}


def _cancel(task: asyncio.Task | None) -> None:
    if task is not None and not task.done():
        task.cancel()


def reset_runtime(channel_id: int) -> bool:
    """チャンネルのメモリ内状態（保留発言・タイマ等）をリセットする。"""
    runtime = _runtimes.pop(channel_id, None)
    if runtime is None:
        return False
    _cancel(runtime.task)
    _cancel(runtime.idle_task)
    for task in runtime.append_tasks:
        _cancel(task)
    return True


def shutdown(cog: Any) -> None:
    for channel_id in list(_runtimes):
        reset_runtime(channel_id)


async def on_message(cog: Any, message: Any) -> None:
    guild = getattr(message, "guild", None)
    author = getattr(message, "author", None)
    channel = getattr(message, "channel", None)
    if guild is None or author is None or channel is None:
        return
    current = settings(guild.id)
    kind = classify_message(
        enabled=current["enabled"],
        target_channel_id=current["channel_id"],
        channel_id=getattr(channel, "id", None),
        is_bot=bool(getattr(author, "bot", False)),
        is_webhook=getattr(author, "webhook_id", None) is not None,
        content=getattr(message, "content", ""),
        has_attachment=bool(getattr(message, "attachments", None)),
    )
    if kind != "trigger":
        return
    channel_id = int(channel.id)
    runtime = _runtimes.get(channel_id)
    if runtime is None:
        runtime = _Runtime(guild_id=int(guild.id), channel=channel)
        _runtimes[channel_id] = runtime
    runtime.channel = channel
    runtime.pending.append(message)
    now = time.monotonic()
    runtime.last_message_at = now
    runtime.last_turn_at = now
    runtime.append_tasks = [task for task in runtime.append_tasks if not task.done()]
    runtime.append_tasks.append(asyncio.create_task(_record_turn(runtime, message)))
    _touch_idle_timer(runtime)
    if runtime.task is None or runtime.task.done():
        runtime.task = asyncio.create_task(_worker(runtime))


async def _record_turn(runtime: _Runtime, message: Any) -> None:
    turn = message_to_turn(message)
    if turn is None:
        return
    client = _client()
    if client is None:
        return
    await _db_call(
        "ターン保存",
        lambda: _append_turn_sync(client, int(runtime.channel.id), runtime.guild_id, turn),
    )


async def _flush_appends(runtime: _Runtime) -> None:
    if runtime.append_tasks:
        await asyncio.gather(*runtime.append_tasks, return_exceptions=True)
        runtime.append_tasks.clear()


def _touch_idle_timer(runtime: _Runtime) -> None:
    _cancel(runtime.idle_task)
    runtime.idle_task = asyncio.create_task(_idle_integration(runtime))


async def _idle_integration(runtime: _Runtime) -> None:
    try:
        await asyncio.sleep(MEMORY_IDLE_SECONDS)
        idle = None
        if runtime.last_turn_at is not None:
            idle = time.monotonic() - runtime.last_turn_at
        client = _client()
        if client is None:
            return
        ok, count = await _db_call(
            "未統合件数確認",
            lambda: _count_unintegrated_sync(client, int(runtime.channel.id)),
        )
        if ok and integration_due(int(count), idle):
            await _integrate_memory(runtime, client)
    except asyncio.CancelledError:
        raise
    except Exception:
        logger.exception("Luna AI のアイドル記憶統合でエラーが発生しました: channel=%s", runtime.channel.id)


async def _worker(runtime: _Runtime) -> None:
    try:
        while True:
            while not debounce_due(runtime.last_message_at, time.monotonic(), window=DEBOUNCE_SECONDS):
                remaining = DEBOUNCE_SECONDS - (time.monotonic() - float(runtime.last_message_at or 0.0))
                await asyncio.sleep(min(max(remaining, 0.05), DEBOUNCE_SECONDS))
            state, wait = gate_state(
                runtime.last_reply_at, list(runtime.reply_times), time.monotonic(),
                cooldown=COOLDOWN_SECONDS, limit=MAX_REPLIES_PER_HOUR,
            )
            if state == "cap":
                runtime.pending.clear()
                return
            if state == "cooldown":
                await asyncio.sleep(min(wait, COOLDOWN_SECONDS))
                continue
            batch = runtime.pending
            runtime.pending = []
            # 確率抽選は発言ごとではなく、まとめたバッチごとに1回だけ。
            # 外れてもターンは記録済みで、記憶統合の対象にはなる。
            if roll_reply(settings(runtime.guild_id)["reply_probability"]):
                now = time.monotonic()
                runtime.last_reply_at = now
                runtime.reply_times = deque(prune_reply_times(runtime.reply_times, now))
                runtime.reply_times.append(now)
                await _generate_and_send(runtime, batch)
            client = _client()
            if client is not None:
                ok, count = await _db_call(
                    "未統合件数確認",
                    lambda: _count_unintegrated_sync(client, int(runtime.channel.id)),
                )
                if ok and integration_due(int(count), None):
                    await _integrate_memory(runtime, client)
            if not runtime.pending:
                return
    except asyncio.CancelledError:
        raise
    except Exception:
        logger.exception("Luna AI の応答ワーカーでエラーが発生しました: channel=%s", runtime.channel.id)
    finally:
        runtime.task = None


# ---------------------------------------------------------------- 記憶統合

async def _integrate_memory(runtime: _Runtime, client: Any) -> None:
    channel_id = int(runtime.channel.id)
    ok, turns = await _db_call("未統合ターン取得", lambda: _load_unintegrated_sync(client, channel_id))
    if not ok or not turns:
        return
    key = persona_key(settings(runtime.guild_id).get("custom"))
    _ok, loaded_memory = await _db_call(
        "記憶取得", lambda: _load_memory_sync(client, runtime.guild_id, key))
    memory_text = loaded_memory or ""
    prompt = build_integration_prompt(memory_text, turns)
    try:
        new_memory, _ttft, _total = await _chat_text(
            [
                {"role": "system", "content": INTEGRATION_SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
            max_tokens=4000,
            model=integration_model_name(),
        )
    except (aiohttp.ClientError, asyncio.TimeoutError, logfare.LogfareHTTPError, KiosAPIHTTPError) as exc:
        logger.warning(
            "Luna AI の記憶統合に失敗しました: channel=%s error=%s: %s",
            channel_id, type(exc).__name__, exc)
        return
    new_memory = (new_memory or "").strip()
    if new_memory.startswith("```"):
        new_memory = re.sub(r"^```[a-zA-Z]*\n|\n```$", "", new_memory).strip()
    if not new_memory:
        return
    saved_ok, _saved = await _db_call(
        "記憶保存",
        lambda: _save_memory_sync(client, runtime.guild_id, key, new_memory[:MEMORY_MAX_CHARS]),
    )
    if not saved_ok:
        return
    up_to = max(int(turn.get("id") or 0) for turn in turns)
    await _db_call(
        "統合済み化と剪定",
        lambda: _mark_integrated_and_prune_sync(client, channel_id, up_to),
    )


async def _seed_if_needed(runtime: _Runtime, client: Any) -> None:
    """初回だけ、チャンネルの直近履歴を種ターンとして取り込む。"""
    if runtime.seeded:
        return
    runtime.seeded = True
    channel_id = int(runtime.channel.id)
    _ok, has_turns = await _db_call("種確認", lambda: _has_any_turns_sync(client, channel_id))
    if has_turns:
        return
    try:
        messages: list[Any] = []
        async for message in runtime.channel.history(limit=SEED_HISTORY_LIMIT):
            messages.append(message)
    except Exception:
        logger.warning("Luna AI: 種取り込み用の履歴を取得できませんでした: channel=%s", channel_id)
        return
    for message in reversed(messages):
        author = getattr(message, "author", None)
        if getattr(author, "bot", False) and getattr(author, "display_name", "") != PERSONA_NAME:
            continue
        turn = message_to_turn(message)
        if turn is None:
            continue
        await _db_call(
            "種ターン保存",
            lambda turn=turn: _append_turn_sync(client, channel_id, runtime.guild_id, turn),
        )


