async def _generate_and_send(runtime: _Runtime, batch: list[Any]) -> None:
    loading = await _send_loading(runtime.channel)
    try:
        started_at = time.monotonic()
        channel = runtime.channel
        channel_id = int(channel.id)
        prompt_text = "\n".join(str(getattr(m, "content", "") or "") for m in batch).strip()
        await _flush_appends(runtime)
        memory_text = ""
        turns: list[dict[str, Any]] = []
        client = _client()
        persona = effective_persona(settings(runtime.guild_id).get("custom"))
        if client is not None:
            await _seed_if_needed(runtime, client)
            _ok, loaded_memory = await _db_call(
                "記憶取得", lambda: _load_memory_sync(client, runtime.guild_id, persona["key"]))
            memory_text = loaded_memory or ""
            _ok, loaded = await _db_call(
                "直近ターン取得",
                lambda: _load_recent_turns_sync(client, channel_id, RECENT_TURNS_CONTEXT),
            )
            if loaded:
                turns = loaded
        db_ready_at = time.monotonic()
        context_text = build_context_text(memory_text, turns, luna_name=persona["name"])
        if not context_text:
            fallback = [turn for turn in (message_to_turn(m) for m in batch) if turn]
            context_text = build_context_text("", fallback, luna_name=persona["name"])
        try:
            rag_text = search_rag(prompt_text)
            link_text = ""
            urls = ai_context.extract_urls(prompt_text) if prompt_text else []
            if urls:
                links = await ai_context.fetch_links(urls[: ai_context.MAX_LINKS])
                link_text = _link_blocks(links)
            search_started_at = time.monotonic()
            web_text = await _fetch_web_search_text(prompt_text)
            search_seconds = time.monotonic() - search_started_at
            sections = [context_text] if context_text else []
            if rag_text:
                sections.append(f"【AGO BOT資料】\n{rag_text}")
            if link_text:
                sections.append(link_text)
            if web_text:
                sections.append(f"【Web検索結果】\n{web_text}")
            sections.append("直近の会話の流れ（誰が誰に何を言ったか）を踏まえて、最後の発言に続けて、Lunaとして自然に返信して")
            user_prompt = "\n\n".join(sections)
            attachments = []
            for m in batch:
                attachments.extend(getattr(m, "attachments", None) or [])
                # 返信先のメッセージに付いた画像も、文脈として一緒に見る。
                resolved = getattr(getattr(m, "reference", None), "resolved", None)
                if resolved is not None:
                    attachments.extend(getattr(resolved, "attachments", None) or [])
            user_content = await _build_user_content(user_prompt, attachments)
            system = build_system_prompt(
                persona["system_prompt"], has_materials=bool(rag_text or link_text or web_text))
            messages = [
                {"role": "system", "content": system},
                {"role": "user", "content": user_content},
            ]
            reply, ttft_seconds, stream_seconds = await _chat_text(messages, max_tokens=800)
        except (aiohttp.ClientError, asyncio.TimeoutError, logfare.LogfareHTTPError, KiosAPIHTTPError) as exc:
            logger.warning(
                "Luna AI の生成に失敗しました: channel=%s error=%s: %s",
                channel_id, type(exc).__name__, exc)
            return
        if not reply or not reply.strip():
            return
        avatar = await _resolve_avatar_bytes(persona)
        try:
            await _send_reply(
                channel, reply,
                persona_name=persona["name"],
                persona_icon_url=persona["icon_url"],
                avatar=avatar,
            )
        except (aiohttp.ClientError, asyncio.TimeoutError, discord.HTTPException) as exc:
            logger.warning("Luna AI の送信に失敗しました: channel=%s error=%s", channel_id, exc)
            return
        sent_at = time.monotonic()
        logger.info(
            "Luna AI 応答時間: channel=%s total=%.2fs db=%.2fs search=%.2fs ttft=%.2fs gen=%.2fs send=%.2fs",
            channel_id,
            sent_at - started_at,
            db_ready_at - started_at,
            search_seconds,
            ttft_seconds,
            max(stream_seconds - ttft_seconds, 0.0),
            sent_at - db_ready_at - stream_seconds - search_seconds,
        )
        if client is not None:
            luna_turn = {"author_name": persona["name"], "is_luna": True, "content": reply.strip()}
            await _db_call(
                "Lunaターン保存",
                lambda: _append_turn_sync(client, channel_id, runtime.guild_id, luna_turn),
            )
            runtime.last_turn_at = time.monotonic()
            _touch_idle_timer(runtime)

    finally:
        await _delete_loading(loading)


_icon_bytes_cache: bytes | None = None


def icon_bytes() -> bytes | None:
    """同梱アイコンのバイト列。読めなければ None（アバターなしで続行）。"""
    global _icon_bytes_cache
    if _icon_bytes_cache is None:
        try:
            _icon_bytes_cache = ICON_PATH.read_bytes()
        except OSError:
            try:
                _icon_bytes_cache = base64.b64decode(ICON_B64_PATH.read_text(encoding="ascii"))
            except (OSError, ValueError):
                logger.warning("Luna AI: アイコンアセットを読めませんでした: %s", ICON_B64_PATH)
                return None
    return _icon_bytes_cache


def icon_url() -> str | None:
    """per-send の avatar_url は URL が要るため、環境変数がある場合だけ使う。"""
    return os.getenv("LUNA_AI_ICON_URL", "").strip() or None


async def _ensure_webhook_avatar(webhook: Any, avatar: bytes | None) -> None:
    """既存 webhook にアバターが無ければ、指定バイト列を編集で付ける。"""
    if avatar is None or getattr(webhook, "avatar", None) is not None:
        return
    try:
        await webhook.edit(avatar=avatar)
    except discord.HTTPException as exc:
        logger.warning("Luna AI: webhook アバターを設定できませんでした: %s", exc)


_webhook_cache: dict[int, Any] = {}


def _webhook_parent(channel: Any) -> Any:
    return channel.parent if isinstance(channel, discord.Thread) else channel


def _evict_webhook(channel: Any) -> None:
    parent_id = getattr(_webhook_parent(channel), "id", None)
    if parent_id is not None:
        _webhook_cache.pop(int(parent_id), None)


async def _get_or_create_webhook(channel: Any, avatar: bytes | None = None) -> discord.Webhook:
    parent = _webhook_parent(channel)
    if not isinstance(parent, discord.TextChannel):
        raise RuntimeError("Webhookの親テキストチャンネルを取得できませんでした。")
    parent_id = getattr(parent, "id", None)
    if parent_id is not None:
        cached = _webhook_cache.get(int(parent_id))
        if cached is not None:
            return cached
    if avatar is None:
        avatar = icon_bytes()
    webhook = None
    webhooks = await parent.webhooks()
    for candidate in webhooks:
        if candidate.name == WEBHOOK_NAME:
            await _ensure_webhook_avatar(candidate, avatar)
            webhook = candidate
            break
    if webhook is None:
        if avatar is not None:
            webhook = await parent.create_webhook(name=WEBHOOK_NAME, avatar=avatar)
        else:
            webhook = await parent.create_webhook(name=WEBHOOK_NAME)
    if parent_id is not None:
        _webhook_cache[int(parent_id)] = webhook
    return webhook


_custom_icon_cache: dict[str, bytes | None] = {}


async def _fetch_icon_bytes(url: str) -> bytes | None:
    """カスタムアイコンを URL から取得する。失敗時は None（呼び出し側で既定に落とす）。"""
    if url in _custom_icon_cache:
        return _custom_icon_cache[url]
    data: bytes | None = None
    try:
        timeout = aiohttp.ClientTimeout(total=10)
        async with aiohttp.ClientSession(timeout=timeout) as session:
            async with session.get(url) as response:
                if response.status == 200:
                    body = await response.read()
                    if 0 < len(body) <= 2 * 1024 * 1024:
                        data = body
    except (aiohttp.ClientError, asyncio.TimeoutError):
        data = None
    if data is None:
        logger.warning("Luna AI: カスタムアイコンを取得できませんでした: %s", url)
    _custom_icon_cache[url] = data
    return data


async def _resolve_avatar_bytes(persona: dict[str, Any]) -> bytes | None:
    """webhook アバター用のバイト列を決める: カスタムURL → 取得失敗なら既定アイコン。"""
    url = persona.get("icon_url")
    if url:
        fetched = await _fetch_icon_bytes(str(url))
        if fetched is not None:
            return fetched
    return icon_bytes()


async def _send_reply(
    channel: Any,
    text: str,
    *,
    persona_name: str = PERSONA_NAME,
    persona_icon_url: str | None = None,
    avatar: bytes | None = None,
) -> None:
    webhook = await _get_or_create_webhook(channel, avatar)
    kwargs: dict[str, Any] = dict(
        username=persona_name,
        allowed_mentions=discord.AllowedMentions.none(),
        _agobot_skip_localization=True,
        wait=True,
    )
    url = persona_icon_url or icon_url()
    if url is not None:
        kwargs["avatar_url"] = url
    if isinstance(channel, discord.Thread):
        kwargs["thread"] = channel
    for index, part in enumerate(split_response(sanitize_output(text))):
        if index:
            await asyncio.sleep(SEND_INTERVAL_SECONDS)
        try:
            await webhook.send(content=part, **kwargs)
        except discord.NotFound:
            # webhook が削除されていたらキャッシュを捨てて取り直し、1回だけ再送する。
            _evict_webhook(channel)
            webhook = await _get_or_create_webhook(channel, avatar)
            await webhook.send(content=part, **kwargs)


