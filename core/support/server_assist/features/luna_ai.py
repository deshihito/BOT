def validate_custom(name: Any, persona: Any, icon_url: Any) -> tuple[dict[str, Any] | None, str | None]:
    """カスタム人格の入力検証（Zeta の validate_custom_fields の流儀）。

    戻り値: (整形済み dict, None) または (None, エラー文)。
    """
    name = str(name or "").strip()
    persona = str(persona or "").strip()
    icon_url = str(icon_url or "").strip()
    if not name:
        return None, "名前を入力してください。"
    if len(name) > CUSTOM_NAME_MAX_CHARS:
        return None, f"名前は{CUSTOM_NAME_MAX_CHARS}文字以内にしてください。"
    lowered = name.lower()
    if any(word in lowered for word in FORBIDDEN_NAME_WORDS):
        return None, "名前に「discord」「clyde」は使用できません（Discordの制限）。"
    if not persona:
        return None, "人格テキストを入力してください。"
    if len(persona) > CUSTOM_PERSONA_MAX_CHARS:
        return None, f"人格テキストは{CUSTOM_PERSONA_MAX_CHARS}文字以内にしてください。"
    if icon_url:
        if len(icon_url) > CUSTOM_ICON_URL_MAX_CHARS or not icon_url.startswith(("https://", "http://")):
            return None, "アイコンURLは http(s):// から始まるURLにしてください（空欄なら既定アイコン）。"
    return {"name": name, "persona": persona, "icon_url": icon_url}, None


_PERSONA_ID_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
PERSONA_KEY_DEFAULT = "default"
PERSONA_KEY_LEGACY = "custom-legacy"


def _normalize_custom(raw: Any) -> dict[str, Any] | None:
    if not isinstance(raw, dict):
        return None
    cleaned, error = validate_custom(raw.get("name"), raw.get("persona"), raw.get("icon_url"))
    if error is not None or cleaned is None:
        return None
    persona_id = raw.get("id")
    if isinstance(persona_id, str) and _PERSONA_ID_RE.match(persona_id):
        cleaned["id"] = persona_id
    return cleaned


def new_persona_id() -> str:
    """カスタム人格の登録IDを新規発行する（記憶ドキュメントのキーになる）。"""
    return uuid.uuid4().hex[:16]


def persona_key(custom: Any) -> str:
    """記憶ドキュメントの割り当てキーを決める（純関数）。

    既定人格は "default"、カスタムは登録ID。IDを持たない旧カスタムは
    専用の固定キーに寄せる（既定の記憶とは混ざらない）。
    """
    cleaned = _normalize_custom(custom)
    if cleaned is None:
        return PERSONA_KEY_DEFAULT
    return cleaned.get("id") or PERSONA_KEY_LEGACY


def with_persona_id(cleaned: dict[str, Any], existing_custom: Any) -> dict[str, Any]:
    """保存用カスタムにIDを付ける（純関数）: 編集では既存IDを引き継ぎ、
    新規登録では新しいIDを発行する（記憶はIDに紐づく）。"""
    result = dict(cleaned)
    existing = _normalize_custom(existing_custom)
    if existing is not None and existing.get("id"):
        result["id"] = existing["id"]
    elif not result.get("id"):
        result["id"] = new_persona_id()
    return result


def _normalize_probability(raw: Any) -> int:
    """返信確率を 0〜100 の整数に正規化する。不正値は既定の100（純関数）。"""
    if isinstance(raw, bool):
        return 100
    try:
        value = int(raw)
    except (TypeError, ValueError):
        return 100
    return max(0, min(100, value))


def roll_reply(probability: Any, *, rng: Any = None) -> bool:
    """返信確率の抽選（デバウンスでまとめたバッチごとに1回だけ引く）。

    0% は常時外れ、100% は常時当選。rng は 0.0〜1.0 を返す呼び出し可能
    オブジェクトを注入でき、テストで境界を固定できる。
    """
    percent = _normalize_probability(probability)
    if percent <= 0:
        return False
    if percent >= 100:
        return True
    draw = (rng or random.random)()
    return draw * 100 < percent


def normalize_settings(raw: Any) -> dict[str, Any]:
    """guild_settings の生値を {enabled, channel_id, custom} に正規化する（純関数）。

    設置は1サーバー1チャンネルまで。custom はカスタム人格1件（検証を通らない
    ものは落とす）。
    """
    if not isinstance(raw, dict):
        raw = {}
    channel_id: int | None = None
    raw_channel = raw.get("channel_id")
    if raw_channel is None and isinstance(raw.get("channel_ids"), list) and raw["channel_ids"]:
        raw_channel = raw["channel_ids"][0]  # 初期実装（複数）からの移行
    try:
        parsed = int(raw_channel)
        if parsed > 0:
            channel_id = parsed
    except (TypeError, ValueError):
        channel_id = None
    return {
        "enabled": bool(raw.get("enabled", False)),
        "channel_id": channel_id,
        "custom": _normalize_custom(raw.get("custom")),
        "reply_probability": _normalize_probability(raw.get("reply_probability", 100)),
    }


