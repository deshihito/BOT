# ---------------------------------------------------------------- 発火判定（純関数）

def classify_message(
    *,
    enabled: bool,
    target_channel_id: Any,
    channel_id: Any,
    is_bot: bool,
    is_webhook: bool,
    content: Any,
    has_attachment: bool,
) -> str:
    """1発言が Luna の応答対象かを判定する。

    戻り値: ``trigger`` / ``bot`` / ``webhook`` / ``disabled`` /
    ``not_target`` / ``command`` / ``empty``。
    """
    if is_bot:
        return "bot"
    if is_webhook:
        return "webhook"
    if not enabled:
        return "disabled"
    if target_channel_id is None or channel_id != target_channel_id:
        return "not_target"
    text = str(content or "").lstrip()
    if text.startswith(("!", "！", "/")):
        return "command"
    if not text and not has_attachment:
        return "empty"
    return "trigger"


def prune_reply_times(reply_times: Any, now: float, *, window: float = RATE_WINDOW_SECONDS) -> list[float]:
    return [t for t in (reply_times or []) if now - float(t) < window]


def gate_state(
    last_reply_at: Any,
    reply_times: Any,
    now: float,
    *,
    cooldown: float = COOLDOWN_SECONDS,
    limit: int = MAX_REPLIES_PER_HOUR,
    window: float = RATE_WINDOW_SECONDS,
) -> tuple[str, float]:
    """レート制御の判定（純関数）。戻り値: (状態, 待つ秒数)。

    状態は ``ok`` / ``cooldown``（待てば応答可）/ ``cap``（1時間上限に到達）。
    """
    recent = prune_reply_times(reply_times, now, window=window)
    if len(recent) >= limit:
        return "cap", 0.0
    if last_reply_at is not None and now - float(last_reply_at) < cooldown:
        return "cooldown", cooldown - (now - float(last_reply_at))
    return "ok", 0.0


def debounce_due(last_message_at: Any, now: float, *, window: float = DEBOUNCE_SECONDS) -> bool:
    if last_message_at is None:
        return False
    return now - float(last_message_at) >= window


