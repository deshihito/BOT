def _split_sections(guide: str) -> list[tuple[str, str]]:
    sections: list[tuple[str, str]] = []
    heading = "概要"
    body: list[str] = []
    for line in str(guide or "").splitlines():
        if line.startswith("## "):
            if body:
                sections.append((heading, "\n".join(body).strip()))
            heading = line[3:].strip() or "概要"
            body = []
        else:
            body.append(line)
    if body:
        sections.append((heading, "\n".join(body).strip()))
    return [(name, text) for name, text in sections if text]


