JST = datetime.timezone(datetime.timedelta(hours=9))


def pool_for(lang: str | None) -> tuple[str, ...]:
    """言語コードに対応するテーマプール。未知の言語は日本語にフォールバックする。"""
    return THEME_POOLS.get(lang or "ja", THEME_POOL)


def theme_day(now: datetime.datetime | None = None) -> datetime.date:
    """テーマの区切りになる「今日」（JST の日付）。"""
    now = now or datetime.datetime.now(JST)
    if now.tzinfo is None:
        now = now.replace(tzinfo=JST)
    return now.astimezone(JST).date()


def _room_offset(room_name: str) -> int:
    """ルーム名から決まる安定したオフセット（プロセスが変わっても同じ値）。"""
    digest = hashlib.md5(room_name.encode("utf-8")).digest()
    return int.from_bytes(digest[:4], "big")


def theme_for(room_name: str, day: datetime.date, lang: str | None = "ja",
              pool: tuple[str, ...] | None = None) -> str:
    """その日のそのルームの自動テーマを返す。日が進むとプールを順に回る。

    lang はルームの言語（RoomConfig.language）。プールは全言語で並び順が
    そろっているので、同じ日・同じルーム名なら言語によらず同じ話題が選ばれる。
    pool を明示した場合はそちらを優先する（従来の呼び出し互換）。
    """
    pool = pool if pool is not None else pool_for(lang)
    if not pool:
        return ""
    index = (day.toordinal() + _room_offset(room_name)) % len(pool)
    return pool[index]
