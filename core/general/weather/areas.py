def offices_of_block(block_code: str) -> tuple[tuple[str, str], ...]:
    """ブロック配下の (office コード, 表示名) を返す（未知のブロックは空）。"""
    for block, _label, offices in BLOCKS:
        if block == block_code:
            return offices
    return ()


def office_name(code: str | None) -> str | None:
    """office コードの表示名（表に無ければ None）。"""
    if not code:
        return None
    return OFFICE_NAMES.get(str(code))


def resolve_area(query: str | None) -> str | None:
    """コード／名称から office コードを解決する（/quick 等の文字列指定用）。

    - 6桁のコードがそのまま表にあればそれを返す。
    - 表示名の完全一致・部分一致（前方優先）でも解決する。
    - 解決できなければ None。
    """
    if not query:
        return None
    text = str(query).strip()
    if text in OFFICE_NAMES:
        return text
    for code, name in OFFICE_NAMES.items():
        if name == text:
            return code
    for code, name in OFFICE_NAMES.items():
        if name.startswith(text) or text in name:
            return code
    return None
