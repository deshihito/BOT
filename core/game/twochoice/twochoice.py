def pick_questions(rng: random.Random, count: int = QUESTIONS_PER_SESSION) -> list:
    return rng.sample(QUESTIONS, min(count, len(QUESTIONS)))


def tally(votes: dict) -> tuple:
    """{user_id: 'A'|'B'} から (Aの数, Bの数) を返す。"""
    a = sum(1 for v in votes.values() if v == "A")
    return a, len(votes) - a


def minority_side(votes: dict):
    """少数派の側 ('A'|'B')。同数なら None。"""
    a, b = tally(votes)
    if a == b:
        return None
    return "A" if a < b else "B"
