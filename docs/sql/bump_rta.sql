    guild_id text PRIMARY KEY,
    notifications_enabled boolean NOT NULL DEFAULT true,
    updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.bump_rta_settings ADD COLUMN IF NOT EXISTS notifications_enabled boolean NOT NULL DEFAULT true;
ALTER TABLE public.bump_rta_settings ADD COLUMN IF NOT EXISTS role_id text;
ALTER TABLE public.bump_rta_settings DROP COLUMN IF EXISTS channel_id;
ALTER TABLE public.bump_rta_settings DROP COLUMN IF EXISTS disboard_bot_id;
ALTER TABLE public.bump_rta_settings DROP COLUMN IF EXISTS disoku_bot_id;

CREATE TABLE IF NOT EXISTS public.bump_rta_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id text NOT NULL,
    user_id text NOT NULL,
    event_type text NOT NULL CHECK (event_type IN ('bump', 'up', 'legacy', 'vote', 'takasumi', 'dicoall', 'dcafe', 'sharkbot', 'dsio', 'discom')),
    elapsed_ms integer NOT NULL CHECK (elapsed_ms > 0),
    bump_message_id text,
    completed_at timestamptz NOT NULL DEFAULT now(),
    -- 記録時点の順位（最速/最遅 × サーバー内/全体）。記録後に
    -- get_bump_rta_record_ranks で算出して埋める。未算出は NULL。
    rank_fast_local integer,
    rank_fast_global integer,
    rank_slow_local integer,
    rank_slow_global integer,
    -- 記録時点の総合順位（全サービスを通したユーザー単位）。
    rank_all_fast_local integer,
    rank_all_fast_global integer,
    rank_all_slow_local integer,
    rank_all_slow_global integer
);
CREATE INDEX IF NOT EXISTS bump_rta_events_guild_type_time_idx
    ON public.bump_rta_events (guild_id, event_type, completed_at DESC);
CREATE INDEX IF NOT EXISTS bump_rta_events_user_type_time_idx
    ON public.bump_rta_events (user_id, event_type, elapsed_ms ASC);

CREATE TABLE IF NOT EXISTS public.bump_rta_records (
    guild_id text NOT NULL,
    user_id text NOT NULL,
    event_type text NOT NULL CHECK (event_type IN ('bump', 'up', 'legacy', 'vote', 'takasumi', 'dicoall', 'dcafe', 'sharkbot', 'dsio', 'discom')),
    elapsed_ms integer NOT NULL CHECK (elapsed_ms > 0),
    completed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (guild_id, user_id, event_type)
);
CREATE INDEX IF NOT EXISTS bump_rta_records_type_ranking_idx
    ON public.bump_rta_records (guild_id, event_type, elapsed_ms ASC);

CREATE TABLE IF NOT EXISTS public.bump_rta_pending (
    guild_id text NOT NULL,
    event_type text NOT NULL CHECK (event_type IN ('bump', 'up', 'legacy', 'vote', 'takasumi', 'dicoall', 'dcafe', 'sharkbot', 'dsio', 'discom')),
    user_id text,
    bump_message_id text NOT NULL,
    bump_at timestamptz NOT NULL,
